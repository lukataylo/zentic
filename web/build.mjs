// Bundles the in-page TypeScript into the one script ZenticKit injects at
// document-start, main frame only, in the `zentic` WKContentWorld.
//
// Output is committed so an Xcode/SwiftPM build never needs Node. Run
// `npm run build` after changing anything under src/ and commit the result.

import { build, context } from "esbuild";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const version = JSON.parse(readFileSync(join(here, "package.json"), "utf8")).version;

/** @type {import("esbuild").BuildOptions} */
export const options = {
  entryPoints: [join(here, "src", "main.ts")],
  outfile: join(here, "..", "Sources", "ZenticKit", "Resources", "zentic.js"),
  bundle: true,
  format: "iife",
  target: ["safari18"],
  platform: "browser",
  // Whitespace only, so Web Inspector frames still carry real names.
  minifyWhitespace: true,
  minifySyntax: true,
  legalComments: "none",
  loader: { ".css": "text" },
  define: { __ZENTIC_VERSION__: JSON.stringify(version) },
  banner: { js: "/* Zentic in-page bundle — generated by web/build.mjs. Do not edit. */" },
  logLevel: "info",
};

const invokedDirectly =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  if (process.argv.includes("--watch")) {
    const ctx = await context(options);
    await ctx.watch();
    console.log("watching web/src -> " + options.outfile);
  } else {
    await build(options);
    console.log("built " + options.outfile);
  }
}
