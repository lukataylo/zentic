// Bundles the in-page TypeScript into the two scripts ZenticKit injects, main
// frame only, in the `zentic` WKContentWorld:
//
//   zentic.js          the core — modes, Minimal, custom versions, scroll. At
//                      document-start, so a page never paints in the wrong mode.
//   zentic-consent.js  cookie-wall dismissal (autoconsent + its rules). At
//                      document-end, and a no-op on Original pages. It is most
//                      of the code by weight, so it stays off the path to first
//                      paint.
//   zentic-passwords.js  sign-in detection and AutoFill. At document-end; adds
//                      listeners and nothing else until a login field is used.
//   zentic-recorder.js  copies the JSON a library source's page fetches. The
//                      page's world, document-start, sources only.
//   zentic-app.js      `window.zentic` for generated apps (not injected: served).
//
// Output is committed so an Xcode/SwiftPM build never needs Node. Run
// `npm run build` after changing anything under src/ and commit the result.

import { build, context } from "esbuild";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const version = JSON.parse(readFileSync(join(here, "package.json"), "utf8")).version;
const resources = join(here, "..", "Sources", "ZenticKit", "Resources");

/** Big JSON as a string literal: a scan to load, parsed only when used. */
const jsonAsText = {
  name: "json-as-text",
  setup(b) {
    b.onLoad({ filter: /compact-rules\.json$/ }, (args) => ({
      contents: `export default ${JSON.stringify(readFileSync(args.path, "utf8"))};`,
      loader: "js",
    }));
  },
};

/** @returns {import("esbuild").BuildOptions} */
function bundle(entry, name) {
  return {
    entryPoints: [join(here, "src", entry)],
    outfile: join(resources, name),
    bundle: true,
    format: "iife",
    target: ["safari18"],
    platform: "browser",
    // Parsed on every navigation in every tab, so every byte counts.
    // Identifiers are kept so Web Inspector frames still carry real names.
    minifyWhitespace: true,
    minifySyntax: true,
    legalComments: "none",
    loader: { ".css": "text" },
    plugins: [jsonAsText],
    define: { __ZENTIC_VERSION__: JSON.stringify(version) },
    banner: { js: "/* Zentic in-page bundle — generated by web/build.mjs. Do not edit. */" },
    logLevel: "info",
  };
}

export const bundles = [
  bundle("main.ts", "zentic.js"),
  bundle("consent-entry.ts", "zentic-consent.js"),
  bundle("passwords-entry.ts", "zentic-passwords.js"),
  // The one script in a page's *own* world, on library sources only. Separate,
  // so nothing else of Zentic's ever runs where page script can see it.
  bundle("recorder-entry.ts", "zentic-recorder.js"),
  // `window.zentic` for generated apps, served from each app's own origin.
  bundle("app-runtime.ts", "zentic-app.js"),
];

const invokedDirectly =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  for (const options of bundles) {
    if (process.argv.includes("--watch")) {
      await (await context(options)).watch();
    } else {
      await build(options);
    }
    console.log("built " + options.outfile);
  }
}
